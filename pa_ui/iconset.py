"""Vector icons as plain data, so they need no font and look the same on every phone.

Android's default Kivy font has no emoji, so icons are drawn from strokes instead. Each icon is a
list of primitives in a unit square (0..1, y up):
    ("l", [(x, y), ...], closed)   a stroked polyline (closed=True joins the ends)
    ("d", x, y, r)                 a filled dot
"""
import math


def _arc(cx, cy, r, a0, a1, n=14):
    return [(cx + r * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
             cy + r * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]


def _circle(cx, cy, r, n=28):
    return _arc(cx, cy, r, 0, 360, n)[:-1]


def _star():
    pts = []
    for i in range(10):
        r = 0.42 if i % 2 == 0 else 0.18
        a = math.radians(90 + i * 36)
        pts.append((0.5 + r * math.cos(a), 0.5 + r * math.sin(a) - 0.03))
    return pts


def _heart():
    pts = []
    for i in range(40):
        t = 2 * math.pi * i / 40
        x = 16 * math.sin(t) ** 3
        y = 13 * math.cos(t) - 5 * math.cos(2 * t) - 2 * math.cos(3 * t) - math.cos(4 * t)
        pts.append((0.5 + x / 38.0, 0.52 + y / 38.0))
    return pts


